def slugify(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def new(num: str, tag: str = "", name: str | None = None, out: str | None = None) -> None:
    """vk new paper.pdf [--name slug] [--out videos/]   or, inside a workspace with papers.json, vk new 03."""
    if num.lower().endswith(".pdf"):
        pdf_path = Path(num).resolve()
        if not pdf_path.exists():
            sys.exit(f"{pdf_path} not found")
        import pymupdf
        title = (pymupdf.open(str(pdf_path)).metadata or {}).get("title") or pdf_path.stem
        p = {"short_name": name or slugify(pdf_path.stem), "title": title, "filename": str(pdf_path)}
        video = Path(out or "videos").resolve() / (p["short_name"] + tag)
    else:
        papers = json.loads((ROOT / "papers.json").read_text())
        p = next((x for x in papers if x["short_name"].startswith(f"{int(num):02}_")), None)
        if not p:
            sys.exit(f"no paper {num} in papers.json")
        nn, rest = p["short_name"].split("_", 1)
        video = ROOT / "videos" / (f"{nn}{tag}_{rest}" if tag else p["short_name"])
    if (video / "video.toml").exists() or (video / "video.py").exists():
        sys.exit(f"{video} already exists")
    for d in ("assets", "build", "out", "qa"):
        (video / d).mkdir(parents=True, exist_ok=True)
    pdf = (ROOT / p["filename"]).resolve()
    (video / "paper.pdf").symlink_to(pdf)
    (video / "video.py").write_text(
        '"""' + p["title"] + ' : paper walkthrough. Build: vk build . all -q h"""\n'
        "from vk.walk import *\n\n"
        "# colour legend (one colour per concept, used everywhere)\n\n\n"
        "class Paper(Video):\n"
        f"    title = {json.dumps(p['title'])}\n\n"
        '    @chapter("Title and abstract")\n'
        "    def title_abstract(self, p):\n"
        '        self.beat("...", go=p.block("..."))\n')
    (video / "pronounce.toml").write_text('# Extra pronunciations for this video (regex = spoken). Example:\n[pronounce]\n'
                                          '# "\\\\bGEPA\\\\b" = "jeppa"\n')
    meta = {k: p[k] for k in ("title", "conference", "year", "paper_url", "pdf_urls") if k in p}
    (video / "paper_meta.json").write_text(json.dumps(meta, indent=1))
    kit = KIT / "bin" / "vk"
    subprocess.run([str(kit), "paper", "text", str(pdf), "--out", str(video / "build" / "paper.txt")], check=True)
    subprocess.run([str(kit), "paper", "figures", str(pdf), "--out", str(video / "assets" / "auto")], check=True,
                   stdout=subprocess.DEVNULL)
    print(f"scaffolded {video}\n  paper text: build/paper.txt\n  auto crops: assets/auto/ (verify overlays in assets/auto/_detect/)")


# ---------------------------------------------------------------- cli
def main(argv=None):
    if argv and argv[0] == "new":
        ap = argparse.ArgumentParser(prog="vk new")
        ap.add_argument("_"); ap.add_argument("num", help="paper.pdf (or a paper number in a papers.json workspace)")
        ap.add_argument("--tag", default="", help="version tag: vk new 3 --tag v4 -> videos/03v4_<name>/")
        ap.add_argument("--name", help="folder name for a PDF (default: from the file name)")
        ap.add_argument("--out", help="parent folder for a PDF (default: ./videos)")
        a = ap.parse_args(argv)
        new(a.num, a.tag, a.name, a.out)
        return
    ap = argparse.ArgumentParser(prog="vk build", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("video", type=Path)
    ap.add_argument("step", choices=["check", "tts", "render", "concat", "all", "stats"])
    ap.add_argument("-q", "--quality", choices=list(QUALITY), default="l")
    ap.add_argument("--only")
    ap.add_argument("--jobs", type=int, default=2)
    ap.add_argument("--force", action="store_true", help="re-render even unchanged chapters")
    a = ap.parse_args(argv)
    video = a.video.resolve()
    cfg = load(video)
    scenes = selected(cfg, a.only)
    if not scenes:
        sys.exit("no scenes listed in video.toml (or --only matched none)")
    sys.path.insert(0, str(KIT))
    if a.step == "stats":
        stats(video, cfg)
    if a.step in ("check", "all") and cfg.get("program"):
        if tts_prepass(video, cfg, scenes, fast=True):
            sys.exit("check failed: fix every problem listed above, then re-run")
    if a.step in ("tts", "all") or (a.step == "check" and not cfg.get("program")):
        rc = tts_prepass(video, cfg, scenes)
        if rc and a.step == "all" and cfg.get("program"):
            sys.exit("voice pass failed: fix the error above before rendering")
    if a.step in ("render", "all"):
        if not render(video, scenes, a.quality, a.jobs, a.force):
            sys.exit(1)
    if a.step in ("concat", "all"):
        if concat(video, cfg, a.quality) is None:
            sys.exit(1)


if __name__ == "__main__":
    main(sys.argv[1:])
