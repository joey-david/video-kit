def tts_prepass(video: Path, cfg: dict, scenes: list[dict], fast: bool = False) -> int:
    if cfg.get("program"):
        payload = json.dumps([{"stem": s["stem"]} for s in cfg["scene"]])
        env = env_for(video)
        if fast:
            env["VK_FAST"] = "1"
        r = subprocess.run([str(VENV_PY), "-c", PREPASS_PROGRAM, str(video), payload, cfg["program"]], cwd=video,
                           env=env)
        return r.returncode
    payload = json.dumps([{"stem": s["stem"], "file": s["file"], "cls": s["cls"]} for s in scenes])
    r = subprocess.run([str(VENV_PY), "-c", PREPASS, str(video), payload], cwd=video, env=env_for(video))
    stats(video, cfg)
    return r.returncode


def stats(video: Path, cfg: dict) -> None:
    mf = video / "build" / "manifest.json"
    if not mf.exists():
        print("no build/manifest.json yet; run `tts` first")
        return
    m = json.loads(mf.read_text())
    order = [s["stem"] for s in cfg["scene"]]
    total = sum(x["dur"] for x in m)
    words = sum(len(x["spoken"].split()) for x in m)
    print(f"\nnarration total: {total / 60:.1f} min, {words} words, {len(m)} lines "
          f"(target 10-15 min of narration; scene transitions add ~2-5%)")
    for st in order:
        d = sum(x["dur"] for x in m if x["scene"] == st)
        print(f"  {st:28} {d / 60:5.2f} min")


# ---------------------------------------------------------------- render
def render_one(video: Path, s: dict, q: str) -> tuple[str, bool, str]:
    from vk.slots import slot

    flag, fps, _ = QUALITY[q]
    media = video / "media" / s["stem"]
    log = video / "build" / f"render_{s['stem']}_{q}.log"
    log.parent.mkdir(exist_ok=True)
    cmd = [str(MANIM), flag, "--fps", str(fps), "--disable_caching", "--media_dir", str(media),
           "--progress_bar", "none", s["file"], s["cls"]]
    t0 = time.time()
    with slot("render"):
        with open(log, "w") as fh:
            r = subprocess.run(cmd, cwd=video, env=env_for(video), stdout=fh, stderr=subprocess.STDOUT)
    ok = r.returncode == 0 and scene_mp4(video, s, q) is not None
    tail = "" if ok else "\n".join(log.read_text().splitlines()[-25:])
    return s["stem"], ok, f"{time.time() - t0:.0f}s" if ok else tail


def scene_mp4(video: Path, s: dict, q: str) -> Path | None:
    res = QUALITY[q][2]
    hits = list((video / "media" / s["stem"] / "videos").glob(f"*/{res}/{s['cls']}.mp4"))
    return hits[0] if hits else None


def chapter_hashes(video: Path, scenes: list[dict], q: str) -> dict[str, str]:
    """Per-chapter fingerprint (video.py mode): the chapter's own source + everything shared (rest of video.py,
    anims*.py, pronounce.toml, the kit's code) + its starting camera. Unchanged chapters are not re-rendered."""
    import hashlib
    src = (video / "video.py").read_text()
    tree = ast.parse(src)
    own, shared = {}, src
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and any(getattr(getattr(d, "func", None), "id", "") == "chapter"
                                                     for d in node.decorator_list):
            seg = ast.get_source_segment(src, node) or ""
            own[node.name] = seg
            shared = shared.replace(seg, "")
    extra = "".join(f.read_text() for f in sorted(video.glob("anims*.py")))
    extra += (video / "pronounce.toml").read_text() if (video / "pronounce.toml").exists() else ""
    extra += "".join(f.read_text() for f in sorted((KIT / "vk").glob("*.py")))
    cams = json.loads((video / "build" / "camera.json").read_text()) if (video / "build" / "camera.json").exists() else []
    out = {}
    for i, sc in enumerate(scenes):
        name = sc["stem"].split("_", 1)[1]
        cam = json.dumps(cams[i]) if i < len(cams) else ""
        out[sc["stem"]] = hashlib.sha1((own.get(name, "") + shared + extra + cam + q).encode()).hexdigest()
    return out


def render(video: Path, scenes: list[dict], q: str, jobs: int, force: bool = False) -> bool:
    all_ok = True
    if (video / "video.py").exists():
        allsc = load(video)["scene"]
        hashes = chapter_hashes(video, allsc, q)
        todo = []
        for s in scenes:
            hf = video / "media" / s["stem"] / f".hash_{q}"
            if not force and hf.exists() and hf.read_text() == hashes[s["stem"]] and scene_mp4(video, s, q):
                print(f"cached {s['stem']}", flush=True)
            else:
                todo.append(s)
        scenes = todo
    else:
        hashes = {}
    with cf.ThreadPoolExecutor(max_workers=jobs) as ex:
        for stem, ok, info in ex.map(lambda s: render_one(video, s, q), scenes):
            print(f"{'done  ' if ok else 'FAILED'} {stem}  {info if ok else ''}", flush=True)
            if ok and stem in hashes:
                (video / "media" / stem / f".hash_{q}").write_text(hashes[stem])
            if not ok:
                all_ok = False
                print(info)
    lint_report(video, load(video)["scene"] if (video / "video.py").exists() else scenes)
    return all_ok


def lint_report(video: Path, scenes: list[dict]) -> None:
    lines = []
    for s in scenes:
        f = video / "media" / s["stem"] / "vk" / f"{s['cls']}.lint.txt"
        if f.exists() and f.read_text().strip():
            lines.append(f"[{s['stem']}]\n" + f.read_text())
    if lines:
        out = video / "build" / "lint.txt"
        out.write_text("\n".join(lines))
        n = sum(len(x.splitlines()) - 1 for x in lines)
        print(f"layout lint: {n} warning(s) -> {out}  (text overlaps / off-frame / dead air; fix or justify)")
    else:
        (video / "build" / "lint.txt").unlink(missing_ok=True)
        print("layout lint: clean")


# ---------------------------------------------------------------- concat
def fmt_ts(t: float, srt: bool = True) -> str:
    h, rem = divmod(t, 3600)
    m, s = divmod(rem, 60)
    if srt:
        return f"{int(h):02}:{int(m):02}:{int(s):02},{int((s - int(s)) * 1000):03}"
    return f"{int(h)}:{int(m):02}:{int(s):02}" if h else f"{int(m)}:{int(s):02}"


def probe(path: Path) -> float:
    return float(subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0",
                                          str(path)]).decode().strip())


def concat(video: Path, cfg: dict, q: str) -> Path | None:
    out = video / "out"
    pad_dir = video / "build" / "padded"
    pad_dir.mkdir(parents=True, exist_ok=True)
    out.mkdir(exist_ok=True)
    listing, meta, srt, yt, events = [], [";FFMETADATA1"], [], [], []
    t, n = 0.0, 0
    missing = [s["stem"] for s in cfg["scene"] if scene_mp4(video, s, q) is None]
    if missing:
        print(f"missing renders at quality {q}: {missing}")
        return None
    for s in cfg["scene"]:
        src = scene_mp4(video, s, q)
        padded = pad_dir / f"{s['stem']}_{q}.mov"
        has_audio = bool(subprocess.run(["ffprobe", "-v", "error", "-select_streams", "a", "-show_entries", "stream=index",
                                         "-of", "csv=p=0", str(src)], capture_output=True, text=True).stdout.strip())
        if has_audio:  # pad the narration to the video length so audio/video stay in sync across scenes
            cmd = ["ffmpeg", "-loglevel", "error", "-y", "-i", str(src), "-filter_complex",
                   "[0:a:0]aresample=48000,aformat=channel_layouts=stereo,apad[a]", "-map", "0:v", "-map", "[a]",
                   "-c:v", "copy", "-c:a", "pcm_s16le", "-shortest", "-f", "mov", str(padded)]
        else:  # silent scene: add a silent track
            cmd = ["ffmpeg", "-loglevel", "error", "-y", "-i", str(src), "-f", "lavfi", "-i", "anullsrc=r=48000:cl=stereo",
                   "-map", "0:v", "-map", "1:a", "-c:v", "copy", "-c:a", "pcm_s16le", "-t", f"{probe(src)}", "-f", "mov",
                   str(padded)]
        subprocess.run(cmd, check=True)
        d = probe(padded)
        listing.append(f"file '{padded}'")
        meta += ["[CHAPTER]", "TIMEBASE=1/1000", f"START={int(t * 1000)}", f"END={int((t + d) * 1000)}",
                 f"title={s.get('chapter', s['stem'])}"]
        yt.append(f"{fmt_ts(t, srt=False)} {s.get('chapter', s['stem'])}")
        ev = video / "media" / s["stem"] / "vk" / f"{s['cls']}.events.json"
        if ev.exists():
            for e in json.loads(ev.read_text()):
                events.append({**e, "t": round(t + min(e["t"], d - 0.05), 2), "chapter": s.get("chapter", s["stem"])})
        cap = video / "media" / s["stem"] / "vk" / f"{s['cls']}.captions.json"
        if cap.exists():
            for c in json.loads(cap.read_text()):
                for a, b, text in split_caption(c["start"], c["end"], c["text"]):
                    n += 1
                    srt.append(f"{n}\n{fmt_ts(t + a)} --> {fmt_ts(t + b)}\n{text}\n")
        t += d
    (video / "build" / "list.txt").write_text("\n".join(listing) + "\n")
    (video / "build" / "chapters.txt").write_text("\n".join(meta) + "\n")
    name = video.name + ("" if q == "h" else "_preview")
    dst = out / f"{name}.mp4"
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-f", "concat", "-safe", "0", "-i", str(video / "build" / "list.txt"),
                    "-i", str(video / "build" / "chapters.txt"), "-map_metadata", "1", "-map", "0:v", "-map", "0:a",
                    "-c:v", "copy", "-af", "loudnorm=I=-14:TP=-1.5:LRA=11", "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
                    "-movflags", "+faststart", str(dst)], check=True)
    (out / f"{name}.srt").write_text("\n".join(srt))
    (out / f"{name}_chapters.txt").write_text("\n".join(yt) + "\n")
    (out / f"{name}_events.json").write_text(json.dumps(events, indent=0))
    print(f"wrote {dst}  ({t / 60:.1f} min)\n      {out / (name + '.srt')}\n      {out / (name + '_chapters.txt')}")
    return dst


def split_caption(a: float, b: float, text: str, max_chars: int = 84):
    """Split a narration line into subtitle-sized pieces, timed proportionally to characters."""
    text = re.sub(r"`", "", text)
    words, pieces, cur = text.split(), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > max_chars:
            pieces.append(cur)
            cur = w
        else:
            cur = f"{cur} {w}".strip()
    if cur:
        pieces.append(cur)
    total = sum(len(p) for p in pieces) or 1
    t = a
    for p in pieces:
        d = (b - a) * len(p) / total
        yield t, t + d, p
        t += d


