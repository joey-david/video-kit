def _video_program(video: Path) -> dict | None:
    """video.py mode: one program, chapters = methods decorated with @chapter("Title") in a Video subclass.
    Writes build/chapters.py with one thin Scene class per chapter for manim to render."""
    src = video / "video.py"
    if not src.exists():
        return None
    tree = ast.parse(src.read_text())
    cls_name, title, chs = None, video.name, []
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        found = []
        for item in node.body:
            if isinstance(item, ast.FunctionDef):
                for d in item.decorator_list:
                    if isinstance(d, ast.Call) and getattr(d.func, "id", "") == "chapter" and d.args:
                        found.append((item.name, ast.literal_eval(d.args[0])))
            if isinstance(item, ast.Assign) and any(getattr(t, "id", "") == "title" for t in item.targets):
                try:
                    title = ast.literal_eval(item.value)
                except Exception:
                    pass
        if found:
            cls_name, chs = node.name, found
    if not cls_name:
        sys.exit("video.py: no class with @chapter(...) methods found")
    lines = ["# generated by vk build from video.py: one Scene per chapter", "import video as _v", ""]
    scenes = []
    for i, (name, ch) in enumerate(chs):
        cls = f"Ch{i + 1:02d}"
        lines += [f"class {cls}(_v.{cls_name}):", f"    chapter_index = {i}", ""]
        scenes.append({"file": "build/chapters.py", "cls": cls, "stem": f"c{i + 1:02d}_{name}", "chapter": ch})
    (video / "build").mkdir(exist_ok=True)
    (video / "build" / "chapters.py").write_text("\n".join(lines))
    return {"title": title, "scene": scenes, "program": cls_name}


def load(video: Path) -> dict:
    prog = _video_program(video)
    if prog:
        return prog
    cfg = tomllib.loads((video / "video.toml").read_text())
    cfg.setdefault("scene", [])
    for s in cfg["scene"]:
        s["stem"] = Path(s["file"]).stem
    return cfg


def env_for(video: Path) -> dict:
    env = dict(os.environ)
    env["PYTHONPATH"] = f"{KIT}:{video}" + (f":{env['PYTHONPATH']}" if env.get("PYTHONPATH") else "")
    env["VK_VIDEO_DIR"] = str(video)
    env["PYTHONWARNINGS"] = "ignore"
    env["TOKENIZERS_PARALLELISM"] = "false"
    env["OMP_NUM_THREADS"] = "1"
    return env


def selected(cfg: dict, only: str | None) -> list[dict]:
    if not only:
        return cfg["scene"]
    want = set(only.split(","))
    return [s for s in cfg["scene"] if s["stem"] in want or s["cls"] in want]


